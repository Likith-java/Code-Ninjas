"""
Professional Excel (XLSX) workbook generator for Everest Textile Intelligence using openpyxl.
Features styled summaries, auto-filtered data tables, frozen headers, and formula sanitization.
"""
import io
from typing import Any
from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from app.services.report_service import ReportData

# Brand Styles
FILL_PRIMARY = PatternFill(start_color="0E4B3E", end_color="0E4B3E", fill_type="solid")
FILL_SECONDARY = PatternFill(start_color="7D988B", end_color="7D988B", fill_type="solid")
FILL_ACCENT = PatternFill(start_color="FAF7F0", end_color="FAF7F0", fill_type="solid")
FILL_ZEBRA = PatternFill(start_color="F7F5EE", end_color="F7F5EE", fill_type="solid")

FONT_TITLE = Font(name="Calibri", size=16, bold=True, color="0E4B3E")
FONT_SUBTITLE = Font(name="Calibri", size=11, bold=True, color="181816")
FONT_TH = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
FONT_TH_SEC = Font(name="Calibri", size=10, bold=True, color="FFFFFF")
FONT_DATA = Font(name="Calibri", size=10, color="181816")
FONT_MUTED = Font(name="Calibri", size=9, italic=True, color="555550")
FONT_KPI_VAL = Font(name="Calibri", size=14, bold=True, color="0E4B3E")
FONT_KPI_LBL = Font(name="Calibri", size=9, bold=True, color="555550")

THIN_BORDER_SIDE = Side(border_style="thin", color="D8D0C0")
BORDER_CELL = Border(
    left=THIN_BORDER_SIDE,
    right=THIN_BORDER_SIDE,
    top=THIN_BORDER_SIDE,
    bottom=THIN_BORDER_SIDE,
)


def _sanitize_cell(val: Any) -> Any:
    """Neutralize potential CSV/Excel formula injection vectors."""
    if isinstance(val, str):
        trimmed = val.strip()
        if trimmed.startswith(("=", "+", "-", "@")):
            return f"'{trimmed}"
    return val


def generate_excel_report(data: ReportData) -> bytes:
    """Generate structured multi-sheet XLSX report from ReportData in memory."""
    wb = Workbook()

    # -------------------------------------------------------------
    # Sheet 1: Summary & Executive KPIs
    # -------------------------------------------------------------
    ws_summary = wb.active
    ws_summary.title = "Executive Summary"
    ws_summary.views.sheetView[0].showGridLines = True

    # Title Banner
    ws_summary["A1"] = "EVEREST TEXTILE MILLS"
    ws_summary["A1"].font = Font(name="Calibri", size=10, bold=True, color="7D988B")

    ws_summary["A2"] = data.title
    ws_summary["A2"].font = FONT_TITLE

    # Metadata Card
    meta_rows = [
        ("Authorized Target:", data.audience),
        ("Report Scope Window:", data.date_range_str),
        ("Generated By:", data.generated_by),
        ("Timestamp:", data.generated_at.strftime("%Y-%m-%d %H:%M:%S UTC")),
        ("Classification:", "CONFIDENTIAL & PROPRIETARY"),
    ]

    for idx, (label, val) in enumerate(meta_rows, start=4):
        ws_summary[f"A{idx}"] = label
        ws_summary[f"A{idx}"].font = Font(name="Calibri", size=10, bold=True, color="555550")
        ws_summary[f"B{idx}"] = _sanitize_cell(val)
        ws_summary[f"B{idx}"].font = FONT_DATA

    # KPI Table
    start_kpi_row = 11
    ws_summary[f"A{start_kpi_row}"] = "KEY OPERATIONAL PERFORMANCE INDICATORS"
    ws_summary[f"A{start_kpi_row}"].font = FONT_SUBTITLE

    kpi_hdr_row = start_kpi_row + 1
    kpi_headers = ["Metric Label", "Value", "Unit", "Operational Scope"]
    for col_idx, h in enumerate(kpi_headers, start=1):
        cell = ws_summary.cell(row=kpi_hdr_row, column=col_idx, value=h)
        cell.font = FONT_TH
        cell.fill = FILL_PRIMARY
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = BORDER_CELL

    curr_row = kpi_hdr_row + 1
    for k in data.kpis:
        c1 = ws_summary.cell(row=curr_row, column=1, value=_sanitize_cell(k.label))
        c2 = ws_summary.cell(row=curr_row, column=2, value=_sanitize_cell(k.value))
        c3 = ws_summary.cell(row=curr_row, column=3, value=_sanitize_cell(k.unit))
        c4 = ws_summary.cell(row=curr_row, column=4, value=_sanitize_cell(k.subtext))

        for c in (c1, c2, c3, c4):
            c.font = FONT_DATA
            c.border = BORDER_CELL
            c.fill = FILL_ACCENT

        c2.font = FONT_KPI_VAL
        c2.alignment = Alignment(horizontal="right")
        curr_row += 1

    # Notes
    if data.notes:
        curr_row += 2
        ws_summary.cell(row=curr_row, column=1, value="AUDIT & COMPLIANCE NOTES").font = FONT_SUBTITLE
        curr_row += 1
        for n in data.notes:
            cell = ws_summary.cell(row=curr_row, column=1, value=f"• {_sanitize_cell(n)}")
            cell.font = FONT_MUTED
            curr_row += 1

    # Auto-adjust Summary columns
    for col in ws_summary.columns:
        max_len = max(len(str(cell.value or "")) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws_summary.column_dimensions[col_letter].width = max(max_len + 4, 16)

    # -------------------------------------------------------------
    # Sheet 2: Primary Data Records
    # -------------------------------------------------------------
    ws_data = wb.create_sheet(title="Operational Records")
    ws_data.views.sheetView[0].showGridLines = True

    # Header Row (Row 1)
    for col_idx, h in enumerate(data.headers, start=1):
        cell = ws_data.cell(row=1, column=col_idx, value=h)
        cell.font = FONT_TH
        cell.fill = FILL_PRIMARY
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER_CELL

    ws_data.row_dimensions[1].height = 28
    ws_data.freeze_panes = "A2"  # Freeze top header row

    # Data Rows
    row_idx = 2
    for r in data.rows:
        is_zebra = (row_idx % 2 == 0)
        for col_idx, val in enumerate(r, start=1):
            cell = ws_data.cell(row=row_idx, column=col_idx, value=_sanitize_cell(val))
            cell.font = FONT_DATA
            cell.border = BORDER_CELL
            if is_zebra:
                cell.fill = FILL_ZEBRA

            # Alignment formatting
            if isinstance(val, (int, float)):
                cell.alignment = Alignment(horizontal="right")
            else:
                cell.alignment = Alignment(horizontal="left")

        row_idx += 1

    # Enable Excel Auto-Filter on data columns
    if data.headers and data.rows:
        last_col = get_column_letter(len(data.headers))
        ws_data.auto_filter.ref = f"A1:{last_col}{len(data.rows) + 1}"

    # Auto-adjust Records columns
    for col in ws_data.columns:
        max_len = max(len(str(cell.value or "")) for cell in col)
        col_letter = get_column_letter(col[0].column)
        ws_data.column_dimensions[col_letter].width = max(min(max_len + 4, 40), 14)

    # -------------------------------------------------------------
    # Sheet 3: Secondary Breakdown (if applicable)
    # -------------------------------------------------------------
    if data.secondary_headers and data.secondary_rows:
        sec_title = data.secondary_title or "Supplemental Data"
        sheet_name = sec_title[:31]  # Excel max sheet name length is 31
        ws_sec = wb.create_sheet(title=sheet_name)
        ws_sec.views.sheetView[0].showGridLines = True

        for col_idx, h in enumerate(data.secondary_headers, start=1):
            cell = ws_sec.cell(row=1, column=col_idx, value=h)
            cell.font = FONT_TH_SEC
            cell.fill = FILL_SECONDARY
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
            cell.border = BORDER_CELL

        ws_sec.row_dimensions[1].height = 26
        ws_sec.freeze_panes = "A2"

        s_row_idx = 2
        for r in data.secondary_rows:
            is_zebra = (s_row_idx % 2 == 0)
            for col_idx, val in enumerate(r, start=1):
                cell = ws_sec.cell(row=s_row_idx, column=col_idx, value=_sanitize_cell(val))
                cell.font = FONT_DATA
                cell.border = BORDER_CELL
                if is_zebra:
                    cell.fill = FILL_ZEBRA

                if isinstance(val, (int, float)):
                    cell.alignment = Alignment(horizontal="right")
                else:
                    cell.alignment = Alignment(horizontal="left")

            s_row_idx += 1

        if data.secondary_rows:
            last_sec_col = get_column_letter(len(data.secondary_headers))
            ws_sec.auto_filter.ref = f"A1:{last_sec_col}{len(data.secondary_rows) + 1}"

        for col in ws_sec.columns:
            max_len = max(len(str(cell.value or "")) for cell in col)
            col_letter = get_column_letter(col[0].column)
            ws_sec.column_dimensions[col_letter].width = max(min(max_len + 4, 40), 14)

    # Save to in-memory bytes buffer
    buffer = io.BytesIO()
    wb.save(buffer)
    excel_bytes = buffer.getvalue()
    buffer.close()
    return excel_bytes
